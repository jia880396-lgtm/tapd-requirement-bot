def build_category_tree_text() -> str:
    """构建分类树文本描述，用于LLM prompt"""
    lines = []
    for l1, l2_list in CATEGORY_TREE.items():
        desc = CATEGORY_DESCRIPTIONS.get(l1, {})
        l1_desc = desc.get("_self", "") if isinstance(desc, dict) else str(desc)
        if l2_list:
            lines.append(f"### {l1}（{l1_desc}）")
            for l2 in l2_list:
                l2_desc = desc.get(l2, "") if isinstance(desc, dict) else ""
                lines.append(f"  - {l2}：{l2_desc}")
        else:
            lines.append(f"### {l1}（{l1_desc}）")
    return "\n".join(lines)


def build_term_mapping_text() -> str:
    """构建术语映射文本"""
    lines = []
    for term, (meaning, module) in TERM_MAPPING.items():
        mod_str = f" -> {module}" if module else ""
        lines.append(f"- {term}：{meaning}{mod_str}")
    return "\n".join(lines)


def build_rules_text() -> str:
    """构建跨模块规则文本"""
    return "\n".join(f"{i+1}. {r}" for i, r in enumerate(CROSS_MODULE_RULES))
